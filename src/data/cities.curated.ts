export interface City {
  id: string;
  name: string;
  lat: number;
  lng: number;
  founded: number;
  abandoned?: number;
  note?: string;
  /** Optional Wikipedia article slug. Defaults to `name` if omitted. */
  wikipedia?: string;
  /**
   * Optional `[year, population_thousands]` anchors. Values are interpolated
   * linearly. If omitted, the city renders at a constant default size.
   */
  populationCurve?: ReadonlyArray<[number, number]>;
  /**
   * Optional ISO 3166-1 alpha-2 country code (e.g. "US", "FR", "JP"). Used by
   * the population layer to bucket cities to their country accurately. Always
   * set on cities generated from GeoNames; usually omitted on curated entries
   * (mostly ancient/historical cities where modern country boundaries don't
   * apply cleanly).
   */
  cc?: string;
  /**
   * Whether this city is the national capital of its country. Auto-set from
   * GeoNames PPLC feature codes by the build script; can be set manually on
   * curated entries that override a modern capital (e.g. constantinople).
   */
  capital?: boolean;
}

/** Linear interpolation across a city's population curve. Returns thousands. */
export function cityPopulationAt(city: City, year: number): number {
  const c = city.populationCurve;
  if (!c || c.length === 0) return 0;
  if (year <= c[0][0]) return c[0][1];
  if (year >= c[c.length - 1][0]) return c[c.length - 1][1];
  for (let i = 1; i < c.length; i += 1) {
    const [ya, va] = c[i - 1];
    const [yb, vb] = c[i];
    if (year >= ya && year <= yb) {
      const t = (year - ya) / (yb - ya);
      return va + (vb - va) * t;
    }
  }
  return 0;
}

