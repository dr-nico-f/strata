export function activeLanguageStage(lang: LanguageFamily, year: number): LanguageStage | undefined {
  let chosen: LanguageStage | undefined;
  for (const stage of lang.stages) {
    if (stage.startYear <= year) chosen = stage;
    else break;
  }
  return chosen;
}
